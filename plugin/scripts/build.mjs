// Build lib/client.js from src/client.js + skin.css + lens.svg.
//
// DSH serves a client plugin as ONE self-contained script in the client
// module-loader format:
//
//   window.__ModuleLoader__.load({ id, factory: (require) => { ... } })
//
// The loader does not resolve relative imports (an ESM `import` fails with
// "import failed (see console for the import error)" and blocks the whole web
// boot), so the CSS and the lens markup must be inlined into that single file.
// This script does exactly that, and nothing else.
import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const root = path.join(here, '..')
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')

const packageJson = JSON.parse(read('package.json'))
const body = read('src/client.js')
const css = read('skin.css')
const svg = read('lens.svg')

// String literals via JSON.stringify: safe for backticks, ${, backslashes and
// every character the CSS or SVG may contain.
const banner = [
  '// GENERATED by scripts/build.mjs — edit src/client.js, skin.css or lens.svg.',
  `// package: ${packageJson.name}@${packageJson.version}`,
  '',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(packageJson.name)},`,
  '  factory: (require) => {',
  '    var module = { exports: {} }',
  '    var exports = module.exports',
  '',
  `    var SKIN_CSS = ${JSON.stringify(css)}`,
  '',
  `    var LENS_SVG = ${JSON.stringify(svg)}`,
  '',
].join('\n')

const footer = [
  '',
  '    exports.name = name',
  '    exports.inject = inject',
  '    exports.apply = apply',
  '    return module.exports',
  '  },',
  '})',
  '',
].join('\n')

const out = `${banner}\n${body}\n${footer}`
const outPath = path.join(root, 'lib', 'client.js')
fs.writeFileSync(outPath, out, 'utf8')

// --- verification -----------------------------------------------------------
// A build that cannot be parsed and cannot produce its exports is worse than no
// build at all, because the failure only shows up as a blank "Failed to load
// plugins" page in the running app.

// 1. syntax: as a classic script (not a module)
new vm.Script(out, { filename: 'lib/client.js' })

// 2. behaviour: run it against a stub loader and a stub DOM
const captured = []
const node = () => ({
  children: [],
  setAttribute() {},
  getAttribute: () => null,
  removeAttribute() {},
  hasAttribute: () => false,
  appendChild(child) { this.children.push(child); return child },
  remove() {},
  querySelector: () => null,
  querySelectorAll: () => [],
  addEventListener() {},
  removeEventListener() {},
  set textContent(v) { this._text = v },
  get textContent() { return this._text },
  set innerHTML(v) { this._html = v },
  get innerHTML() { return this._html },
})
const sandbox = {
  window: { __ModuleLoader__: { load: (entry) => captured.push(entry) } },
  document: {
    head: node(),
    body: { ...node(), attributes: new Set(), setAttribute(k) { this.attributes.add(k) }, removeAttribute(k) { this.attributes.delete(k) }, hasAttribute(k) { return this.attributes.has(k) } },
    createElement: node,
  },
  MutationObserver: class {
    observe() {}
    disconnect() {}
  },
}
vm.createContext(sandbox)
vm.runInContext(out, sandbox)

if (captured.length !== 1) throw new Error(`expected one loader call, got ${captured.length}`)
const entry = captured[0]
if (entry.id !== packageJson.name) throw new Error(`loader id ${entry.id} != ${packageJson.name}`)

const setThemeCalls = []
const effects = []
const theme = {
  getTheme: () => ({ preference: 'light' }),
  setTheme(id) { setThemeCalls.push(id) },
}
const moduleExports = entry.factory(() => ({}))
const ctx = {
  theme,
  effect(fn) { effects.push(fn()) },
}
if (typeof moduleExports.apply !== 'function') throw new Error('bundle did not export apply()')
if (!Array.isArray(moduleExports.inject)) throw new Error('bundle did not export inject[]')
moduleExports.apply(ctx)

const pageBody = sandbox.document.body
if (!pageBody.hasAttribute('data-dsh-skin-moss-550c')) throw new Error('skin attribute was not set on body')
if (!pageBody.hasAttribute('data-ds-dark-theme')) throw new Error('dark scheme attribute was not set on body')

// The shipped stylesheet must carry the palette, and it must out-specify the
// built-in dark palette ([data-ds-dark-theme] = 0,1,0). The exact colour is a
// design decision that changes often, so assert only that the token carries a
// value — a literal hex here breaks on every palette tweak.
if (!/--dsw-alias-bg-base:\s*#[0-9a-f]{3,8}/i.test(css)) {
  throw new Error('stylesheet is missing the base palette')
}
// Comments may contain braces, so locate the rule on a comment-free copy.
const cssNoComments = css.replace(/\/\*[\s\S]*?\*\//g, '')
const skinScope = 'body[data-dsh-skin-moss-550c] {'
const scopeAt = cssNoComments.indexOf(skinScope)
if (scopeAt < 0) throw new Error('palette scope block not found')
const paletteBlock = cssNoComments.slice(scopeAt, cssNoComments.indexOf('}', scopeAt))
for (const token of ['--dsw-alias-bg-base', '--dsw-specific-sidebar-fill', '--dsw-alias-brand-primary', '--dsw-alias-label-primary']) {
  if (!paletteBlock.includes(token)) throw new Error(`palette scope is missing ${token}`)
}

const lens = pageBody.children?.find?.((c) => c.id === 'moss-lens-wrap')
if (!lens) throw new Error('lens wrapper was not mounted')

// The iris must keep its own tracking wrapper: the pointer offset is written to
// .m-iris-track while the breathing scale stays on .m-iris, and collapsing the
// two breaks the follow-the-cursor effect silently.
if (!svg.includes('m-iris-track')) {
  throw new Error('lens.svg lost the .m-iris-track wrapper')
}
if (!css.includes('.m-iris-track')) {
  throw new Error('stylesheet lost the .m-iris-track rule')
}
const lensMarkup = `${lens.innerHTML ?? ''}`
const tagCount = (lensMarkup.match(/m-tag/g) ?? []).length

const mark = pageBody.children?.find?.((c) => c.id === 'moss-mark')
if (!mark) throw new Error('550W watermark was not mounted')
if (!`${mark.innerHTML ?? ''}`.includes('wm-zero')) throw new Error('red zero glyph was replaced by a bare inline element')
if (!`${mark.innerHTML ?? ''}`.includes('550W [MOSS]')) throw new Error('watermark caption missing')

const balance = pageBody.children?.find?.((c) => c.id === 'moss-balance')
if (!balance) throw new Error('balance widget was not mounted')
if (!`${balance.innerHTML ?? ''}`.includes('mb-burn')) throw new Error('token-burn bar missing from the balance chip')

for (const dispose of effects) if (typeof dispose === 'function') dispose()

const kb = (n) => `${(n / 1024).toFixed(1)} KB`
console.log(`built ${path.relative(root, outPath)} — ${kb(Buffer.byteLength(out))}`)
console.log(`  loader id    : ${entry.id}`)
console.log(`  exports      : ${Object.keys(moduleExports).join(', ')}`)
console.log(`  palette      : ${(paletteBlock.match(/--dsw-[a-z-]+/g) ?? []).length} tokens scoped to body[data-dsh-skin-moss-550c]`)
console.log(`  scheme       : rides built-in "${setThemeCalls[0] ?? 'none'}"`)
console.log(`  lens         : ${tagCount} HUD tags mounted`)
console.log(`  css inlined  : ${kb(Buffer.byteLength(css))}`)
console.log(`  svg inlined  : ${kb(Buffer.byteLength(svg))}`)
console.log('  syntax + behaviour verified in a VM sandbox')
